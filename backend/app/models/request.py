"""
A request a caller made on a call, recorded for the team.

The agent cannot book, cancel or escalate anything. What it can do is write
down exactly what the caller asked for, with a reference the caller can
quote, and leave it where the team will see it. Before this existed the agent
said "your complaint has been submitted" and invented `CMP-20261108-01`;
nothing was written anywhere.

Stored in `voice_requests` as `(id, tenant_id, data jsonb)`, like every
sibling table. The reference is generated by the repository, never by the
model.
"""
from __future__ import annotations

import time
import uuid
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class RequestType(str, Enum):
    TEST_DRIVE = "test_drive"
    SERVICE = "service"
    COMPLAINT = "complaint"
    CALLBACK = "callback"
    QUESTION = "question"
    CANCELLATION = "cancellation"
    OTHER = "other"


#: The letters a reference starts with, by type. Complaints use exactly the
#: form a client's own handbook told the agent to give (`CMP-YYYYMMDD-NN`),
#: so the handbook and the system now say the same thing.
PREFIXES: dict[RequestType, str] = {
    RequestType.TEST_DRIVE: "TD",
    RequestType.SERVICE: "SRV",
    RequestType.COMPLAINT: "CMP",
    RequestType.CALLBACK: "CB",
    RequestType.QUESTION: "REQ",
    RequestType.CANCELLATION: "CXL",
    RequestType.OTHER: "REQ",
}


class RequestStatus(str, Enum):
    NEW = "new"
    IN_PROGRESS = "in_progress"
    DONE = "done"


class ReplyBy(str, Enum):
    CALL = "call"
    WHATSAPP = "whatsapp"


#: What the team needs before a request is worth recording, by type. Every
#: type needs the four common ones; a question needs only a number to answer
#: to and the question itself, and nobody is pressed for a name over it.
COMMON_FIELDS = ("name", "mobile", "city", "details")
REQUIRED_FIELDS: dict[RequestType, tuple[str, ...]] = {
    RequestType.TEST_DRIVE: COMMON_FIELDS + ("vehicle_model", "preferred_times"),
    RequestType.SERVICE: COMMON_FIELDS + ("vehicle_model", "registration", "preferred_times"),
    RequestType.COMPLAINT: COMMON_FIELDS,
    RequestType.CALLBACK: COMMON_FIELDS,
    RequestType.QUESTION: ("mobile", "details"),
    RequestType.CANCELLATION: COMMON_FIELDS,
    RequestType.OTHER: COMMON_FIELDS,
}
#: One of these must be present, per type, on top of the required fields.
EITHER_OF: dict[RequestType, tuple[str, ...]] = {
    RequestType.COMPLAINT: ("vehicle_model", "registration"),
    RequestType.CANCELLATION: ("registration", "booking_reference"),
}

#: How each field is named when the agent is told what is still missing.
LABELS = {
    "name": "the caller's name",
    "mobile": "a mobile number",
    "city": "the city",
    "location": "the location or branch",
    "details": "what the request is about",
    "vehicle_model": "the vehicle model",
    "registration": "the registration number",
    "mileage": "the mileage",
    "preferred_times": "a preferred day and time",
    "booking_reference": "the booking reference",
    "occupation": "their occupation",
    "purchase_timeline": "when they plan to buy",
}
#: Fields a request may carry but never needs. Asked for only if the
#: material says to, and dropped the moment the caller would rather not say.
OPTIONAL_FIELDS = ("occupation", "purchase_timeline", "location", "mileage")


def missing_fields(kind: RequestType, values: dict[str, Any]) -> list[str]:
    """The fields still needed before `kind` can be recorded, as labels."""
    def has(name: str) -> bool:
        value = values.get(name)
        if isinstance(value, list):
            return any(str(v).strip() for v in value)
        return bool(str(value or "").strip())

    missing = [LABELS[f] for f in REQUIRED_FIELDS[kind] if not has(f)]
    either = EITHER_OF.get(kind)
    if either and not any(has(f) for f in either):
        if kind is RequestType.CANCELLATION:
            # A booking reference is read out of `details` when there is no
            # registration; either will do.
            if not _mentions_reference(values.get("details")):
                missing.append(" or ".join(LABELS[f] for f in either))
        else:
            missing.append(" or ".join(LABELS[f] for f in either))
    return missing


def _mentions_reference(details: Any) -> bool:
    import re

    return bool(re.search(r"\b[A-Z]{2,4}-?\d{4,}", str(details or "")))


class RecordedRequest(BaseModel):
    """One request. Serialised into `voice_requests.data`."""

    model_config = ConfigDict(populate_by_name=True)

    id: str = Field(default_factory=lambda: uuid.uuid4().hex)
    tenant_id: str = Field(default="", alias="tenantId")
    call_id: str = Field(default="", alias="callId")
    reference: str = ""
    #: The reference's parts, kept apart so the daily counter is one query.
    prefix: str = ""
    reference_day: str = Field(default="", alias="referenceDay")

    type: RequestType = RequestType.OTHER
    status: RequestStatus = RequestStatus.NEW
    note: str = ""

    name: str = ""
    mobile: str = ""
    city: str = ""
    location: str = ""
    preferred_times: list[str] = Field(default_factory=list, alias="preferredTimes")
    vehicle_model: str = Field(default="", alias="vehicleModel")
    registration: str = ""
    mileage: str = ""
    details: str = ""
    # Offered, never required: a caller who does not want to say what they
    # do is still a caller who wants a test drive.
    occupation: str = ""
    purchase_timeline: str = Field(default="", alias="purchaseTimeline")
    reply_by: ReplyBy = Field(default=ReplyBy.CALL, alias="replyBy")
    #: The number the call was with, for the team; the caller may have given
    #: a different one to be reached on.
    caller_number: str = Field(default="", alias="callerNumber")

    created_at: float = Field(default_factory=time.time, alias="createdAt")
    updated_at: float = Field(default_factory=time.time, alias="updatedAt")

    def public(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "tenantId": self.tenant_id,
            "callId": self.call_id or None,
            "reference": self.reference,
            "type": self.type.value,
            "status": self.status.value,
            "note": self.note or None,
            "name": self.name or None,
            "mobile": self.mobile or None,
            "city": self.city or None,
            "location": self.location or None,
            "preferredTimes": list(self.preferred_times),
            "vehicleModel": self.vehicle_model or None,
            "registration": self.registration or None,
            "mileage": self.mileage or None,
            "details": self.details or None,
            "occupation": self.occupation or None,
            "purchaseTimeline": self.purchase_timeline or None,
            "replyBy": self.reply_by.value,
            "callerNumber": self.caller_number or None,
            "createdAt": self.created_at,
            "updatedAt": self.updated_at,
        }

    def one_line(self) -> str:
        """For the call's summary: "TD-20261111-01, test drive, SEAL Premium,
        Lahore, Sat 9:30-10:30, 0300 123 4567"."""
        from ..services.agent.phones import grouped, parse

        shown_mobile = self.mobile
        parsed = parse(self.mobile) if self.mobile else None
        if parsed:
            shown_mobile = grouped(parsed[1])
        parts = [self.reference, self.type.value.replace("_", " ")]
        for value in (self.vehicle_model, self.registration, self.city, self.location,
                      ", ".join(self.preferred_times), shown_mobile):
            if value:
                parts.append(value)
        if self.details:
            parts.append(self.details[:120])
        return ", ".join(parts)


class RequestUpdate(BaseModel):
    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    status: RequestStatus | None = None
    note: str | None = Field(default=None, max_length=2000)
